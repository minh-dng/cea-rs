use cea_rs::{
    Error,
    rocket::{RocketOptions, Station},
    solver::Solver,
    thermo::Reactant,
};

fn model(names: &[&str], only: Option<Vec<String>>) -> Solver {
    Solver::new(
        names.iter().map(|n| Reactant::named(n).unwrap()).collect(),
        true,
        false,
        only,
        vec![],
    )
    .unwrap()
}

fn values(st: &Station) -> [f64; 15] {
    let s = &st.state;
    [
        s.temperature_k,
        s.pressure_pa,
        s.density_kg_m3,
        s.enthalpy_j_kg,
        s.entropy_j_kg_k,
        s.gamma_s,
        s.molecular_weight_kg_kmol,
        st.mach,
        st.sound_speed_m_s,
        st.area_ratio.unwrap_or(0.0),
        st.cstar_m_s,
        st.thrust_coefficient,
        st.isp_m_s,
        st.isp_vacuum_m_s,
        st.velocity_m_s,
    ]
}

#[test]
fn rocket_stations_match_independent_native_goldens() {
    // Generated by scripts/compare_rocket_parity.py with cea==3.3.4, not Rust.
    // The fixture includes RP-1311 8–12 (11 uses a Li reference) and freeze/state/stop cases.
    let fixture = include_str!("rocket-native.txt");
    let names = ["H2(L)", "O2(L)"];
    for case in [
        "8",
        "9",
        "10",
        "11-reference",
        "12-eq",
        "12-fr",
        "freeze-3",
        "freeze-5",
        "freeze-omit",
        "fac-fr",
        "fac-fr-5",
        "assigned-t",
        "assigned-h",
        "assigned-est",
        "frozen-stop",
        "condensed-stop",
        "freeze-subar",
        "pressure-range",
    ] {
        let mut o = RocketOptions::default();
        let mut solver = model(&names, None);
        let (mut weights, mut temperatures, mut pc) =
            (vec![1.0, 5.55157], vec![20.27, 90.17], 53.3172e5);
        match case {
            "8" | "9" | "10" => {
                o.pi_p = &[10.0, 100.0, 1000.0];
                o.supar = &[25.0, 50.0, 75.0];
                if case == "8" {
                    o.subar = &[1.58];
                } else {
                    o.iac = false;
                    if case == "9" {
                        o.ac_at = Some(1.58);
                    } else {
                        o.mdot = Some(1333.9);
                    }
                }
            }
            "11-reference" => {
                solver = Solver::new(
                    vec![
                        Reactant::custom(
                            "Li-reference".into(),
                            [("Li".into(), 1.0)].into(),
                            6.941,
                            0.0,
                            298.15,
                        )
                        .unwrap(),
                        Reactant::named("F2(L)").unwrap(),
                    ],
                    true,
                    true,
                    None,
                    vec![],
                )
                .unwrap();
                weights = vec![6.941, 0.5556 * 37.9968064];
                temperatures = vec![298.15, 85.02];
                pc = 6_894_757.293_168_572;
                o.pi_p = &[68.0457];
                o.subar = &[10.0];
                o.supar = &[10.0, 20.0, 100.0];
            }
            "12-eq" | "12-fr" => {
                solver = model(&["CH6N2(L)", "N2O4(L)"], Some(
                    "CO CO2 H HNO HNO2 HO2 H2 H2O H2O2 N NO NO2 N2 N2O O OH O2 HCO NH CH4 NH2 NH3 H2O(L) C(gr)"
                    .split_whitespace().map(String::from).collect()));
                weights = vec![1.0, 2.5];
                temperatures = vec![298.15; 2];
                pc = 6_894_757.293_168_572;
                o.pi_p = &[68.0457];
                o.supar = &[5.0, 10.0, 25.0, 50.0, 75.0, 100.0, 150.0, 200.0];
                if case == "12-fr" {
                    o.n_frz = 2;
                }
            }
            "freeze-3" => {
                o.pi_p = &[10.0, 100.0, 1000.0];
                o.supar = &[25.0, 50.0, 75.0];
                o.n_frz = 3;
            }
            "freeze-5" => {
                o.supar = &[2.0, 5.0, 10.0, 25.0, 50.0];
                o.n_frz = 5;
            }
            "freeze-omit" => {
                o.pi_p = &[10.0, 2.0, 100.0];
                o.subar = &[2.0];
                o.supar = &[1.5, 25.0, 10.0, 50.0];
                o.n_frz = 3;
            }
            "fac-fr" | "fac-fr-5" => {
                o.iac = false;
                o.ac_at = Some(1.58);
                o.supar = &[5.0, 25.0, 50.0];
                o.n_frz = if case == "fac-fr" { 4 } else { 5 };
            }
            "assigned-t" => {
                o.tc = Some(3200.0);
                o.pi_p = &[10.0];
                o.subar = &[1.5];
                o.supar = &[5.0, 25.0];
            }
            "assigned-h" => {
                o.hc = Some(1e6);
                o.pi_p = &[10.0];
                o.supar = &[5.0, 25.0];
            }
            "assigned-est" => {
                o.tc_est = Some(3200.0);
                o.supar = &[5.0, 25.0];
            }
            "frozen-stop" => {
                solver = model(&["N2"], None);
                weights = vec![1.0];
                temperatures = vec![300.0];
                o.tc = Some(500.0);
                o.pi_p = &[2.0, 5.0, 10.0, 100.0];
                o.n_frz = 1;
            }
            "condensed-stop" => {
                solver = model(&["CO"], None);
                weights = vec![1.0];
                temperatures = vec![298.15];
                o.tc = Some(900.0);
                o.pi_p = &[2.0, 3.0, 5.0, 10.0, 100.0];
                o.n_frz = 1;
            }
            "freeze-subar" => {
                o.pi_p = &[10.0];
                o.subar = &[1.58];
                o.supar = &[5.0, 25.0];
                o.n_frz = 1;
            }
            "pressure-range" => {
                o.pi_p = &[1.01, 1.1, 2.0, 10.0, 100.0, 1000.0];
            }
            _ => unreachable!(),
        }
        let r = solver
            .rocket_stations(&weights, &temperatures, pc, &o)
            .unwrap_or_else(|e| panic!("{case}: {e}"));
        let rows: Vec<_> = fixture
            .lines()
            .filter(|l| l.split_whitespace().next() == Some(case))
            .collect();
        assert_eq!(r.stations.len(), rows.len(), "{case} station count");
        assert_eq!(
            r.complete,
            !matches!(case, "frozen-stop" | "condensed-stop")
        );
        assert_eq!(
            r.stop_reason.is_some(),
            matches!(case, "frozen-stop" | "condensed-stop")
        );
        let gt = r.throat.state.density_kg_m3 * r.throat.velocity_m_s;
        let h0 = r.stations[0].state.enthalpy_j_kg;
        for (i, (st, row)) in r.stations.iter().zip(rows).enumerate() {
            for (j, (actual, expected)) in values(st)
                .into_iter()
                .zip(
                    row.split_whitespace()
                        .skip(2)
                        .map(|x| x.parse::<f64>().unwrap()),
                )
                .enumerate()
            {
                let error = (actual - expected).abs() / expected.abs().max(1e-9);
                assert!(
                    error < 1e-4,
                    "{case} station {i} field {j}: {actual} vs {expected}, relative error {error}"
                );
            }
            if let Some(area) = st.area_ratio {
                assert!((st.state.density_kg_m3 * st.velocity_m_s * area / gt - 1.0).abs() < 2e-6);
                assert!(
                    (st.state.enthalpy_j_kg + st.velocity_m_s.powi(2) / 2.0 - h0).abs()
                        < 2e-6 * h0.abs().max(1.0)
                );
            }
        }
    }
}

