#[test]
fn native_edge_cases_still_obey_assigned_geometry_and_conservation() {
    let solver = model(&["H2(L)", "O2(L)"], None);
    let pc = 53.3172e5;
    for o in [
        RocketOptions {
            subar: &[100.0],
            ..RocketOptions::default()
        },
        RocketOptions {
            iac: false,
            ac_at: Some(1.0),
            ..RocketOptions::default()
        },
        RocketOptions {
            iac: false,
            ac_at: Some(1.58),
            n_frz: 1,
            supar: &[25.0],
            ..RocketOptions::default()
        },
        RocketOptions {
            iac: false,
            ac_at: Some(1.58),
            n_frz: 2,
            supar: &[25.0],
            ..RocketOptions::default()
        },
        RocketOptions {
            iac: false,
            ac_at: Some(1.58),
            n_frz: 3,
            supar: &[25.0],
            ..RocketOptions::default()
        },
    ] {
        let r = solver
            .rocket_stations(&[1.0, 5.55157], &[20.27, 90.17], pc, &o)
            .unwrap();
        let flux = r.throat.state.density_kg_m3 * r.throat.velocity_m_s;
        assert!((r.throat.mach - 1.0).abs() < 2e-6);
        if let Some(ac) = o.ac_at {
            assert!((r.chamber.area_ratio.unwrap() / ac - 1.0).abs() < 5e-4);
            let chamber = &r.chamber;
            assert!(
                ((chamber.state.pressure_pa
                    + chamber.state.density_kg_m3 * chamber.velocity_m_s.powi(2))
                    / pc
                    - 1.0)
                    .abs()
                    < 2e-6
            );
        } else {
            assert!((r.exit.area_ratio.unwrap() / 100.0 - 1.0).abs() < 5e-4);
        }
        for st in &r.stations {
            if let Some(area) = st.area_ratio {
                assert!(
                    (st.state.density_kg_m3 * st.velocity_m_s * area / flux - 1.0).abs() < 2e-6
                );
                let h0 = r.stations[0].state.enthalpy_j_kg;
                assert!(
                    (st.state.enthalpy_j_kg + st.velocity_m_s.powi(2) / 2.0 - h0).abs()
                        < 2e-6 * h0.abs().max(1.0)
                );
            }
        }
    }
}

#[test]
fn coexisting_alumina_phases_do_not_break_later_nozzle_solves() {
    // Native cea==3.3.4 RocketSolver, NH4CLO4(I)/AL(cr) 4:1 by mass at 298.15 K,
    // supar=80, equilibrium: [chamber T, exit T, c-star, vacuum Isp] in K and m/s.
    let solver = model(&["NH4CLO4(I)", "AL(cr)"], None);
    for (pc, native) in [
        (
            7e6,
            [
                3804.2682518721285,
                2327.000012414637,
                1445.7244492140692,
                3005.515885669441,
            ],
        ),
        (
            20e6,
            [
                3949.292838977873,
                2327.000012414635,
                1456.4897310305407,
                3020.637505987826,
            ],
        ),
    ] {
        let r = solver
            .rocket(
                &[4.0, 1.0],
                &[298.15; 2],
                pc,
                80.0,
                cea_rs::rocket::FlowMode::Equilibrium,
            )
            .unwrap();
        let rust = [
            r.chamber.state.temperature_k,
            r.exit.state.temperature_k,
            r.cstar_m_s,
            r.vacuum_velocity_m_s,
        ];
        for (a, b) in rust.iter().zip(native) {
            assert!((a - b).abs() <= 1e-4 * b, "{pc}: {a} != {b}");
        }
    }
}

