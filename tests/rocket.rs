use cea_rs::{
    Error,
    rocket::{RocketOptions, Station},
    solver::Solver,
    thermo::Reactant,
};

fn model(names: &[&str], only: Option<Vec<String>>) -> Solver {
    Solver::new(
        names.iter().map(|n| Reactant::named(n).unwrap()).collect(),
        true,
        false,
        only,
        vec![],
    )
    .unwrap()
}

fn values(st: &Station) -> [f64; 15] {
    let s = &st.state;
    [
        s.temperature_k,
        s.pressure_pa,
        s.density_kg_m3,
        s.enthalpy_j_kg,
        s.entropy_j_kg_k,
        s.gamma_s,
        s.molecular_weight_kg_kmol,
        st.mach,
        st.sound_speed_m_s,
        st.area_ratio.unwrap_or(0.0),
        st.cstar_m_s,
        st.thrust_coefficient,
        st.isp_m_s,
        st.isp_vacuum_m_s,
        st.velocity_m_s,
    ]
}

#[test]
fn rocket_stations_match_independent_native_goldens() {
    // Generated by scripts/compare_rocket_parity.py with cea==3.3.4, not Rust.
    // The fixture includes RP-1311 8–12 (11 uses a Li reference) and freeze/state/stop cases.
    let fixture = include_str!("rocket-native.txt");
    let names = ["H2(L)", "O2(L)"];
    for case in [
        "8",
        "9",
        "10",
        "11-reference",
        "12-eq",
        "12-fr",
        "freeze-3",
        "freeze-5",
        "freeze-omit",
        "fac-fr",
        "fac-fr-5",
        "assigned-t",
        "assigned-h",
        "assigned-est",
        "frozen-stop",
        "condensed-stop",
        "freeze-subar",
        "pressure-range",
    ] {
        let mut o = RocketOptions::default();
        let mut solver = model(&names, None);
        let (mut weights, mut temperatures, mut pc) =
            (vec![1.0, 5.55157], vec![20.27, 90.17], 53.3172e5);
        match case {
            "8" | "9" | "10" => {
                o.pi_p = &[10.0, 100.0, 1000.0];
                o.supar = &[25.0, 50.0, 75.0];
                if case == "8" {
                    o.subar = &[1.58];
                } else {
                    o.iac = false;
                    if case == "9" {
                        o.ac_at = Some(1.58);
                    } else {
                        o.mdot = Some(1333.9);
                    }
                }
            }
            "11-reference" => {
                solver = Solver::new(
                    vec![
                        Reactant::custom(
                            "Li-reference".into(),
                            [("Li".into(), 1.0)].into(),
                            6.941,
                            0.0,
                            298.15,
                        )
                        .unwrap(),
                        Reactant::named("F2(L)").unwrap(),
                    ],
                    true,
                    true,
                    None,
                    vec![],
                )
                .unwrap();
                weights = vec![6.941, 0.5556 * 37.9968064];
                temperatures = vec![298.15, 85.02];
                pc = 6_894_757.293_168_572;
                o.pi_p = &[68.0457];
                o.subar = &[10.0];
                o.supar = &[10.0, 20.0, 100.0];
            }
            "12-eq" | "12-fr" => {
                solver = model(&["CH6N2(L)", "N2O4(L)"], Some(
                    "CO CO2 H HNO HNO2 HO2 H2 H2O H2O2 N NO NO2 N2 N2O O OH O2 HCO NH CH4 NH2 NH3 H2O(L) C(gr)"
                    .split_whitespace().map(String::from).collect()));
                weights = vec![1.0, 2.5];
                temperatures = vec![298.15; 2];
                pc = 6_894_757.293_168_572;
                o.pi_p = &[68.0457];
                o.supar = &[5.0, 10.0, 25.0, 50.0, 75.0, 100.0, 150.0, 200.0];
                if case == "12-fr" {
                    o.n_frz = 2;
                }
            }
            "freeze-3" => {
                o.pi_p = &[10.0, 100.0, 1000.0];
                o.supar = &[25.0, 50.0, 75.0];
                o.n_frz = 3;
            }
            "freeze-5" => {
                o.supar = &[2.0, 5.0, 10.0, 25.0, 50.0];
                o.n_frz = 5;
            }
            "freeze-omit" => {
                o.pi_p = &[10.0, 2.0, 100.0];
                o.subar = &[2.0];
                o.supar = &[1.5, 25.0, 10.0, 50.0];
                o.n_frz = 3;
            }
            "fac-fr" | "fac-fr-5" => {
                o.iac = false;
                o.ac_at = Some(1.58);
                o.supar = &[5.0, 25.0, 50.0];
                o.n_frz = if case == "fac-fr" { 4 } else { 5 };
            }
            "assigned-t" => {
                o.tc = Some(3200.0);
                o.pi_p = &[10.0];
                o.subar = &[1.5];
                o.supar = &[5.0, 25.0];
            }
            "assigned-h" => {
                o.hc = Some(1e6);
                o.pi_p = &[10.0];
                o.supar = &[5.0, 25.0];
            }
            "assigned-est" => {
                o.tc_est = Some(3200.0);
                o.supar = &[5.0, 25.0];
            }
            "frozen-stop" => {
                solver = model(&["N2"], None);
                weights = vec![1.0];
                temperatures = vec![300.0];
                o.tc = Some(500.0);
                o.pi_p = &[2.0, 5.0, 10.0, 100.0];
                o.n_frz = 1;
            }
            "condensed-stop" => {
                solver = model(&["CO"], None);
                weights = vec![1.0];
                temperatures = vec![298.15];
                o.tc = Some(900.0);
                o.pi_p = &[2.0, 3.0, 5.0, 10.0, 100.0];
                o.n_frz = 1;
            }
            "freeze-subar" => {
                o.pi_p = &[10.0];
                o.subar = &[1.58];
                o.supar = &[5.0, 25.0];
                o.n_frz = 1;
            }
            "pressure-range" => {
                o.pi_p = &[1.01, 1.1, 2.0, 10.0, 100.0, 1000.0];
            }
            _ => unreachable!(),
        }
        let r = solver
            .rocket_stations(&weights, &temperatures, pc, &o)
            .unwrap_or_else(|e| panic!("{case}: {e}"));
        let rows: Vec<_> = fixture
            .lines()
            .filter(|l| l.split_whitespace().next() == Some(case))
            .collect();
        assert_eq!(r.stations.len(), rows.len(), "{case} station count");
        assert_eq!(
            r.complete,
            !matches!(case, "frozen-stop" | "condensed-stop")
        );
        assert_eq!(
            r.stop_reason.is_some(),
            matches!(case, "frozen-stop" | "condensed-stop")
        );
        let gt = r.throat.state.density_kg_m3 * r.throat.velocity_m_s;
        let h0 = r.stations[0].state.enthalpy_j_kg;
        for (i, (st, row)) in r.stations.iter().zip(rows).enumerate() {
            for (j, (actual, expected)) in values(st)
                .into_iter()
                .zip(
                    row.split_whitespace()
                        .skip(2)
                        .map(|x| x.parse::<f64>().unwrap()),
                )
                .enumerate()
            {
                let error = (actual - expected).abs() / expected.abs().max(1e-9);
                assert!(
                    error < 1e-4,
                    "{case} station {i} field {j}: {actual} vs {expected}, relative error {error}"
                );
            }
            if let Some(area) = st.area_ratio {
                assert!((st.state.density_kg_m3 * st.velocity_m_s * area / gt - 1.0).abs() < 2e-6);
                assert!(
                    (st.state.enthalpy_j_kg + st.velocity_m_s.powi(2) / 2.0 - h0).abs()
                        < 2e-6 * h0.abs().max(1.0)
                );
            }
        }
    }
}

#[test]
fn invalid_fac_and_freeze_inputs_do_not_return_a_result() {
    let solver = model(&["H2", "O2"], None);
    for o in [
        RocketOptions {
            iac: false,
            ..RocketOptions::default()
        },
        RocketOptions {
            iac: false,
            ac_at: Some(2.0),
            mdot: Some(1000.0),
            ..RocketOptions::default()
        },
        RocketOptions {
            iac: false,
            ac_at: Some(f64::NAN),
            ..RocketOptions::default()
        },
        RocketOptions {
            iac: false,
            mdot: Some(1e9),
            ..RocketOptions::default()
        },
        RocketOptions {
            n_frz: 3,
            ..RocketOptions::default()
        },
        RocketOptions {
            pi_p: &[1.0],
            ..RocketOptions::default()
        },
        RocketOptions {
            subar: &[1.0],
            ..RocketOptions::default()
        },
        RocketOptions {
            hc: Some(0.0),
            tc: Some(3000.0),
            ..RocketOptions::default()
        },
        RocketOptions {
            tc_est: Some(f64::NAN),
            ..RocketOptions::default()
        },
    ] {
        assert!(matches!(
            solver.rocket_stations(&[1.0, 6.0], &[298.15; 2], 3e6, &o),
            Err(Error::Input(_))
        ));
    }
}

#[test]
fn native_edge_cases_still_obey_assigned_geometry_and_conservation() {
    let solver = model(&["H2(L)", "O2(L)"], None);
    let pc = 53.3172e5;
    for o in [
        RocketOptions {
            subar: &[100.0],
            ..RocketOptions::default()
        },
        RocketOptions {
            iac: false,
            ac_at: Some(1.0),
            ..RocketOptions::default()
        },
        RocketOptions {
            iac: false,
            ac_at: Some(1.58),
            n_frz: 1,
            supar: &[25.0],
            ..RocketOptions::default()
        },
        RocketOptions {
            iac: false,
            ac_at: Some(1.58),
            n_frz: 2,
            supar: &[25.0],
            ..RocketOptions::default()
        },
        RocketOptions {
            iac: false,
            ac_at: Some(1.58),
            n_frz: 3,
            supar: &[25.0],
            ..RocketOptions::default()
        },
    ] {
        let r = solver
            .rocket_stations(&[1.0, 5.55157], &[20.27, 90.17], pc, &o)
            .unwrap();
        let flux = r.throat.state.density_kg_m3 * r.throat.velocity_m_s;
        assert!((r.throat.mach - 1.0).abs() < 2e-6);
        if let Some(ac) = o.ac_at {
            assert!((r.chamber.area_ratio.unwrap() / ac - 1.0).abs() < 5e-4);
            let chamber = &r.chamber;
            assert!(
                ((chamber.state.pressure_pa
                    + chamber.state.density_kg_m3 * chamber.velocity_m_s.powi(2))
                    / pc
                    - 1.0)
                    .abs()
                    < 2e-6
            );
        } else {
            assert!((r.exit.area_ratio.unwrap() / 100.0 - 1.0).abs() < 5e-4);
        }
        for st in &r.stations {
            if let Some(area) = st.area_ratio {
                assert!(
                    (st.state.density_kg_m3 * st.velocity_m_s * area / flux - 1.0).abs() < 2e-6
                );
                let h0 = r.stations[0].state.enthalpy_j_kg;
                assert!(
                    (st.state.enthalpy_j_kg + st.velocity_m_s.powi(2) / 2.0 - h0).abs()
                        < 2e-6 * h0.abs().max(1.0)
                );
            }
        }
    }
}

#[test]
fn coexisting_alumina_phases_do_not_break_later_nozzle_solves() {
    // Native cea==3.3.4 RocketSolver, NH4CLO4(I)/AL(cr) 4:1 by mass at 298.15 K,
    // supar=80, equilibrium: [chamber T, exit T, c-star, vacuum Isp] in K and m/s.
    let solver = model(&["NH4CLO4(I)", "AL(cr)"], None);
    for (pc, native) in [
        (
            7e6,
            [
                3804.2682518721285,
                2327.000012414637,
                1445.7244492140692,
                3005.515885669441,
            ],
        ),
        (
            20e6,
            [
                3949.292838977873,
                2327.000012414635,
                1456.4897310305407,
                3020.637505987826,
            ],
        ),
    ] {
        let r = solver
            .rocket(
                &[4.0, 1.0],
                &[298.15; 2],
                pc,
                80.0,
                cea_rs::rocket::FlowMode::Equilibrium,
            )
            .unwrap();
        let rust = [
            r.chamber.state.temperature_k,
            r.exit.state.temperature_k,
            r.cstar_m_s,
            r.vacuum_velocity_m_s,
        ];
        for (a, b) in rust.iter().zip(native) {
            assert!((a - b).abs() <= 1e-4 * b, "{pc}: {a} != {b}");
        }
    }
}

#[test]
fn air_jet_a_nozzle_continues_from_the_chamber() {
    // cea==3.3.4, Mixture(["Air", "Jet-A(L)"], products_from_reactants=True),
    // RocketSolver(..., transport=False), weights=[25,1], pc=7 bar, supar=[200],
    // hc=reactants.calc_property(ENTHALPY, weights, [298.15,298.15])/cea.R.
    // The native rocket stops the throat at Mach=0.9999816. Refine that station
    // with native EqSolver SP and Eq. 6.17 to |Mach²-1|<1e-10 for sonic closure.
    // Rows are [T (K), P (Pa), Isp (m/s), area ratio].
    let native = [
        [1675.8650845819666, 700000.0, 0.0, 0.0],
        [1472.26718692791, 384347.40114722203, 735.6035486636265, 1.0],
        [
            225.75993685562185,
            111.46954232281868,
            1887.603352765888,
            199.99958302838894,
        ],
    ];
    let result = model(&["Air", "Jet-A(L)"], None)
        .rocket(
            &[25.0, 1.0],
            &[298.15; 2],
            0.7e6,
            200.0,
            cea_rs::rocket::FlowMode::Equilibrium,
        )
        .unwrap();
    assert_eq!(result.stations.len(), native.len());
    for (station, expected) in result.stations.iter().zip(native) {
        let actual = [
            station.state.temperature_k,
            station.state.pressure_pa,
            station.isp_m_s,
            station.area_ratio.unwrap_or(0.0),
        ];
        for (a, b) in actual.into_iter().zip(expected) {
            assert!(
                (a - b).abs() <= 1e-5 * b.abs(),
                "{}: {a} != {b}",
                station.name
            );
        }
    }
}

